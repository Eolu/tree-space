    #[test]
    fn custom_context_menu_round_trips() {
        let raw = r#"
[[context_menu.rules]]
matches = ["ext:rs", "ext:toml"]
items = ["Open", { command = "cargo fmt", label = "Fmt" }]

[[context_menu.rules]]
matches = ["dir"]
items = [{ command = "foot -D {dir}", label = "Open in Terminal" }, "New Folder"]

[[context_menu.rules]]
matches = ["noext"]
items = [{ command = "sh {path}" }]

[[context_menu.rules]]
matches = ['regex:.*\.lock$']
items = ["Open", { command = "rm {path}", label = "Discard lock" }]
"#;
        let config = parse(raw);
        assert_eq!(config.context_menu.rules.len(), 4);

        let first = &config.context_menu.rules[0];
        assert_eq!(
            first.matches,
            vec![ContextMatch::Ext("rs".to_owned()), ContextMatch::Ext("toml".to_owned())]
        );
        assert!(matches!(first.items[0], ContextAction::Builtin(BuiltinAction::Open)));
        assert!(matches!(
            &first.items[1],
            ContextAction::Command(cmd) if cmd.command == "cargo fmt" && cmd.label.as_deref() == Some("Fmt")
        ));

        let last = &config.context_menu.rules[3];
        assert_eq!(
            last.matches,
            vec![ContextMatch::parse(r"regex:.*\.lock$").unwrap()]
        );

        let reparsed = toml::from_str::<Config>(&toml::to_string(&config).unwrap()).unwrap();
        assert_eq!(config, reparsed);
    }

