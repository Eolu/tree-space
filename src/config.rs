/// Which edge of the screen the panel docks to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum PanelSide {
    #[default]
    Left,
    Right,
}

impl PanelSide {
    /// Both sides, left then right.
    pub const ALL: [PanelSide; 2] = [PanelSide::Left, PanelSide::Right];

    /// The other side ("right" for left, and vice versa).
    pub fn opposite(&self) -> PanelSide {
        match self {
            PanelSide::Left => PanelSide::Right,
            PanelSide::Right => PanelSide::Left,
        }
    }

    /// The lowercase word used in user-facing labels ("left" / "right").
    pub fn name(&self) -> &'static str {
        match self {
            PanelSide::Left => "left",
            PanelSide::Right => "right",
        }
    }
}

