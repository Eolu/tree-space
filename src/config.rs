//! Configuration and XDG persistence.
//!
//! This module owns two concerns:
//!
//! * **`Config`** — the user-facing TOML file at
//!   `$XDG_CONFIG_HOME/tree-space/config.toml` (`~/.config/tree-space/config.toml`).
//!   Every field has a sane default via `#[serde(default)]`, so a minimal file
//!   (or none at all) is valid. Those defaults are not written here: they are
//!   parsed from the shipped `default-config.toml` (see [`builtin`]), which is
//!   the single source of truth for every default value.
//! * **`SessionState`** — small runtime state (last opened root) kept in
//!   `$XDG_STATE_HOME/tree-space/state.toml`. Kept separate from the config so
//!   that re-exporting the config as a "default" for users stays clean.
//!
//! The XDG resolution helpers are pure functions over environment-style inputs
//! so they can be tested without mutating process-global environment variables.

use std::env;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

use regex::Regex;
use serde::{Deserialize, Serialize};

/// The directory name used below all XDG base dirs.
pub const APP_DIR: &str = "tree-space";
/// Name of the config file inside [`APP_DIR`].
pub const CONFIG_FILE: &str = "config.toml";
/// Name of the state file inside [`APP_DIR`].
pub const STATE_FILE: &str = "state.toml";
/// Name of the user stylesheet inside [`APP_DIR`].
pub const STYLE_FILE: &str = "main.css";
/// Default name of the bookmarks list file inside [`APP_DIR`]. The config's
/// `[bookmarks] file` may point elsewhere.
pub const BOOKMARKS_FILE: &str = "bookmarks.toml";

/// The shipping default config, written out on first launch. This is the
/// **single source of truth** for every default value: [`Config::default`] and
/// each section's `Default` are parsed from it (see [`builtin`]). It is kept as
/// a real file (rather than generated by serialization) so it can be commented
/// and laid out for humans.
const DEFAULT_CONFIG: &str = include_str!("../default-config.toml");

/// The shipped default stylesheet, written out beside the config on first
/// launch and used as a fallback when the user's own is missing or unreadable.
pub const DEFAULT_STYLESHEET: &str = include_str!("../style/main.css");

/// The parsed `default-config.toml`, built once. Every `Default` impl delegates
/// here so the file, not this module, decides the defaults.
///
/// Parsing uses [`ShippedRaw`], whose section fields are `Option`s with
/// *(field-level)* `#[serde(default)]`. That keeps the parse free of any call
/// back into a section's own `Default` — and therefore out of [`builtin`]
/// itself — because the shipped file always populates every section. A missing
/// section (or scalar) falls back to the literal schema default on its type,
/// which likewise never re-enters [`builtin`].
fn builtin() -> &'static Config {
    static ONCE: OnceLock<Config> = OnceLock::new();
    ONCE.get_or_init(|| {
        let raw: ShippedRaw = toml::from_str(DEFAULT_CONFIG)
            .expect("default-config.toml must be valid TOML");
        Config {
            panel: raw.panel.unwrap_or_default(),
            tree: raw.tree.unwrap_or_default(),
            startup: raw.startup.unwrap_or_default(),
            context_menu: raw.context_menu.unwrap_or_default(),
            pane_menu: raw.pane_menu.unwrap_or_default(),
            bookmarks: raw.bookmarks.unwrap_or_default(),
        }
    })
}

/// A recursion-free view of `default-config.toml`: every section is optional
/// and defaults to `None`, so deserializing the shipped file never touches a
/// section's `Default` (which would re-enter [`builtin`]).
#[derive(Deserialize)]
struct ShippedRaw {
    #[serde(default)]
    panel: Option<PanelConfig>,
    #[serde(default)]
    tree: Option<TreeConfig>,
    #[serde(default)]
    startup: Option<StartupRoot>,
    #[serde(default)]
    context_menu: Option<ContextMenu>,
    #[serde(default)]
    pane_menu: Option<PaneMenu>,
    #[serde(default)]
    bookmarks: Option<BookmarksConfig>,
}

