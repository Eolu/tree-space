    #[test]
    fn multi_rule_wins_for_a_multi_selection_only() {
        let menu = ContextMenu {
            rules: vec![
                ContextRule::rule(vec![ContextMatch::Multi], builtin_items![Trash, CopyPath]),
                ContextRule::rule(vec![ContextMatch::Dir], builtin_items![Open]),
                ContextRule::rule(vec![ContextMatch::Fallback], builtin_items![Open]),
            ],
        };
        let dir = tempfile::tempdir().unwrap();

        // One selected path: the per-path rule applies.
        assert_eq!(menu.actions_for_selection(dir.path(), 1), builtin_items![Open]);
        // Two or more: the multi rule applies instead.
        assert_eq!(
            menu.actions_for_selection(dir.path(), 2),
            builtin_items![Trash, CopyPath]
        );
        assert_eq!(
            menu.actions_for_selection(dir.path(), 7),
            builtin_items![Trash, CopyPath]
        );
    }

