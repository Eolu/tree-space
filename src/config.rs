/// Resolve `$XDG_CONFIG_HOME` / `$HOME/.config` from explicit inputs.
///
/// `xdg` is the value of `XDG_CONFIG_HOME`, `home` the value of `HOME`. When
/// neither is present the XDG spec mandates falling back to `~/.config`.
fn xdg_config_home(xdg: Option<&str>, home: Option<&str>) -> PathBuf {
    match xdg.filter(|s| !s.is_empty()) {
        Some(dir) => PathBuf::from(dir),
        None => home.map(PathBuf::from).unwrap_or_else(|| PathBuf::from("/")).join(".config"),
    }
}

/// Resolve `$XDG_STATE_HOME` / `$HOME/.local/state` from explicit inputs.
fn xdg_state_home(xdg: Option<&str>, home: Option<&str>) -> PathBuf {
    match xdg.filter(|s| !s.is_empty()) {
        Some(dir) => PathBuf::from(dir),
        None => home.map(PathBuf::from).unwrap_or_else(|| PathBuf::from("/")).join(".local/state"),
    }
}

/// Path of `<app dir>/<file>` below an XDG base directory.
fn app_path(base: &Path, file: &str) -> PathBuf {
    base.join(APP_DIR).join(file)
}

/// Read `XDG_CONFIG_HOME`/`HOME` from the environment. Replaced by
/// [`xdg_config_home`] in tests where determinism matters.
fn config_home_from_env() -> PathBuf {
    let xdg = env::var_os("XDG_CONFIG_HOME").map(|v| v.to_string_lossy().into_owned());
    let home = env::var_os("HOME").map(|v| v.to_string_lossy().into_owned());
    xdg_config_home(xdg.as_deref(), home.as_deref())
}

/// Read `XDG_STATE_HOME`/`HOME` from the environment.
fn state_home_from_env() -> PathBuf {
    let xdg = env::var_os("XDG_STATE_HOME").map(|v| v.to_string_lossy().into_owned());
    let home = env::var_os("HOME").map(|v| v.to_string_lossy().into_owned());
    xdg_state_home(xdg.as_deref(), home.as_deref())
}

/// Absolute path of the config file for the current environment.
pub fn config_file() -> PathBuf {
    app_path(&config_home_from_env(), CONFIG_FILE)
}

/// Absolute path of the state file for the current environment.
pub fn state_file() -> PathBuf {
    app_path(&state_home_from_env(), STATE_FILE)
}

/// Absolute path of the user stylesheet for the current environment.
pub fn style_file() -> PathBuf {
    app_path(&config_home_from_env(), STYLE_FILE)
}

/// Absolute path of the bookmarks list for the current environment, given the
/// configured `[bookmarks] file` (relative to the config directory, or
/// absolute).
pub fn bookmark_file_path(configured: &Path) -> PathBuf {
    resolve_bookmarks_path(&config_home_from_env().join(APP_DIR), configured)
}

/// Resolve a `[bookmarks] file` against `base` (the config file's directory).
fn resolve_bookmarks_path(base: &Path, configured: &Path) -> PathBuf {
    if configured.is_absolute() { configured.to_path_buf() } else { base.join(configured) }
}

/// Expand a leading `~` in a bookmark path (a no-op for ordinary paths). Stored
/// paths are absolute in practice, but a hand-written `~/notes` still works.
pub fn expand_bookmark_path(path: &Path) -> PathBuf {
    match path.to_str().and_then(expand_tilde) {
        Some(expanded) => expanded,
        None => path.to_path_buf(),
    }
}

/// The bookmark list a fresh install starts with: one entry for the home
/// directory. Empty only when `$HOME` is unknown.
pub fn default_bookmarks() -> Vec<Bookmark> {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .filter(|home| !home.as_os_str().is_empty())
        .map(|home| vec![Bookmark { name: String::from("Home"), path: home }])
        .unwrap_or_default()
}

